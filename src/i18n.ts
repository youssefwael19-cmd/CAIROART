export function fmtEgp(value: number, lang: Lang) {
  const n = Math.round(value).toLocaleString("en-US");
  return lang === "ar" ? `${n} ج.م` : `EGP ${n}`;
}

export function fmtDate(iso: string, lang: Lang) {
  const d = new Date(iso);
  return d.toLocaleDateString(lang === "ar" ? "ar-EG" : "en-GB", { day: "numeric", month: "short" });
}

export function fmtTime(iso: string, lang: Lang) {
  const d = new Date(iso);
  return d.toLocaleTimeString(lang === "ar" ? "ar-EG" : "en-GB", { hour: "2-digit", minute: "2-digit" });
}
